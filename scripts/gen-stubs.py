def main():
    created = 0
    for line in open(os.path.join(ROOT, "scripts/stubs.tsv")):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        path, owner, kind, typ, extra = line.split("\t")
        if kind == "L":
            continue
        full = os.path.join(ROOT, path)
        if kind == "K4":
            hpath = os.path.join(os.path.dirname(full), "include", typ + ".h")
            if os.path.exists(full) or os.path.exists(hpath):
                continue
            out = k4(typ, owner, extra)
            os.makedirs(os.path.dirname(hpath), exist_ok=True)
            open(hpath, "w").write(out["h"])
            open(full, "w").write(out["m"])
            created += 2
            continue
        if os.path.exists(full):
            continue
        if kind == "S":
            if typ not in SPECIAL:
                # 0.3 S stubs are written by hand into the tree (PLAN 0.3 §6.3); nothing to generate.
                print(f"skipped {path}: hand-written S stub missing", file=sys.stderr)
                continue
            text = SPECIAL[typ](owner)
        elif kind == "K6":
            text = k6(typ, owner, extra)
        elif kind == "K7":
            text = k7(typ, owner, extra)
        else:
            text = KINDS[kind](typ, owner, extra)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        open(full, "w").write(text)
        created += 1
    print(f"created {created} files")


if __name__ == "__main__":
    sys.exit(main())
