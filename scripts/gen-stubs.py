def header(owner, imports):
    return "".join(f"import {i}\n" for i in imports) + f"\n// Stub (owner: {owner}). Generated by scripts/gen-stubs.py; the owner replaces it.\n\n"


def k1(t, owner, extra):
    if extra == "struct":
        body = f"package struct {t}: Codable, Equatable, Sendable {{\n    package init() {{}}\n}}\n"
    else:
        body = f"package enum {t} {{}}\n"
    return header(owner, ["Foundation"]) + body


